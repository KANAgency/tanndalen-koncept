/**
 * Generates TD @font-face + typography utility classes from tokens.
 * Source: typography-styles-tanndalen.json + primitives.json
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const TOKENS = join(ROOT, "tokens");
const OUT_DIR = join(ROOT, "generated");
const STYLES_FILE = join(OUT_DIR, "typography-td.css");
const FONTS_FILE = join(OUT_DIR, "fonts-td.css");

/** Resolved from generated/*.css → design-system/fonts/ */
const FONT_URL_BASE = "../fonts";

function loadJson(name) {
  return JSON.parse(readFileSync(join(TOKENS, name), "utf8"));
}

/** @param {string} familyRef e.g. TD.primary */
function fontFamilyStack(familyRef, weight) {
  const [brand, role] = familyRef.split(".");
  const cssVar = `--font-family-${brand}-${role}`;
  if (brand === "TD" && role === "primary") {
    return `var(${cssVar}), var(--font-family-TD-primary-fallback), serif`;
  }
  if (brand === "TD" && role === "secondary" && weight === "bold") {
    return `"CircularXX", var(${cssVar}), sans-serif`;
  }
  return `var(${cssVar}), sans-serif`;
}

/** @param {string} familyRef @param {string} weight */
function fontWeightCss(familyRef, weight) {
  if (familyRef === "TD.secondary" && weight === "bold") {
    return "700";
  }
  if (weight === "book") {
    return "var(--font-weight-book)";
  }
  if (weight === "bold") {
    return "var(--font-weight-bold)";
  }
  return "var(--font-weight-regular)";
}

function generateFontsCss() {
  const lines = [];
  lines.push("/* Generated by scripts/generate-typography-css.mjs — do not edit by hand. */");
  lines.push("");
  lines.push("/* Webfont files: /ds/fonts/ (shared/design-system/fonts) */");
  lines.push("");

  const faces = [
    {
      family: "Superclarendon",
      file: "Superclarendon-Regular-01.ttf",
      format: "truetype",
      weight: "100 500",
    },
    {
      family: "Superclarendon",
      file: "Superclarendon-Bold-06.ttf",
      format: "truetype",
      weight: "600 900",
    },
    {
      family: "CircularXX TT",
      file: "CircularXX-Book.otf",
      format: "opentype",
      weight: "100 500",
    },
    {
      family: "CircularXX TT",
      file: "CircularXX-Bold.otf",
      format: "opentype",
      weight: "600 900",
    },
    {
      family: "CircularXX",
      file: "CircularXX-Book.otf",
      format: "opentype",
      weight: "400",
    },
    {
      family: "CircularXX",
      file: "CircularXX-Bold.otf",
      format: "opentype",
      weight: "700",
    },
  ];

  for (const face of faces) {
    if (face.note) {
      lines.push(`/* ${face.note} */`);
    }
    lines.push("@font-face {");
    lines.push(`  font-family: ${JSON.stringify(face.family)};`);
    lines.push(`  src: url("${FONT_URL_BASE}/${face.file}") format("${face.format}");`);
    lines.push(`  font-weight: ${face.weight};`);
    lines.push("  font-style: normal;");
    lines.push("  font-display: swap;");
    lines.push("}");
    lines.push("");
  }

  return `${lines.join("\n")}`;
}

function leadingCss(leading) {
  return typeof leading === "number" ? String(leading) : `var(--font-leading-${leading})`;
}

function trackingCss(tracking) {
  return typeof tracking === "number" ? `${tracking}em` : `var(--font-tracking-${tracking})`;
}

function generateTypographyCss() {
  const styles = loadJson("typography-styles-tanndalen.json");
  const lines = [];
  lines.push("/* Generated by scripts/generate-typography-css.mjs — do not edit by hand. */");
  lines.push("/* Requires tokens.css (+ fonts-td.css for webfonts). */");
  lines.push("");

  /** @type {Record<string, string[]>} */
  const aliasesOf = {};
  for (const [name, def] of Object.entries(styles)) {
    if (name.startsWith("$") || typeof def !== "object" || def === null || !def.alias) continue;
    (aliasesOf[def.alias] ??= []).push(name);
  }

  /** @type {string[]} */
  const mobile = [];

  for (const [name, def] of Object.entries(styles)) {
    if (name.startsWith("$") || typeof def !== "object" || def === null || def.alias) continue;
    const { family, size, weight, leading, tracking, textCase } = def;
    if (!family || !size || !weight) continue;

    const names = [name, ...(aliasesOf[name] ?? [])];
    const selector = names.map((n) => `.td-${n}`).join(",\n");
    lines.push(`${selector} {`);
    lines.push(`  font-family: ${fontFamilyStack(family, weight)};`);
    if (name === "heading-2-hero") {
      lines.push("  font-size: clamp(2.5rem, 4vw + 1.5rem, var(--font-size-6xl));");
    } else {
      lines.push(`  font-size: var(--font-size-${size});`);
    }
    lines.push(`  font-weight: ${fontWeightCss(family, weight)};`);
    lines.push(`  line-height: ${leadingCss(leading)};`);
    lines.push(`  letter-spacing: ${trackingCss(tracking)};`);
    lines.push("  font-style: normal;");
    lines.push("  font-synthesis: none;");
    lines.push("  text-rendering: geometricPrecision;");
    if (textCase === "uppercase") {
      lines.push("  text-transform: uppercase;");
    }
    lines.push("}");
    lines.push("");

    if (def.mobile && (def.mobile.size || def.mobile.tracking != null)) {
      mobile.push(`${selector} {`);
      if (def.mobile.size) mobile.push(`  font-size: var(--font-size-${def.mobile.size});`);
      if (def.mobile.tracking != null) mobile.push(`  letter-spacing: ${def.mobile.tracking}em;`);
      mobile.push("}");
      mobile.push("");
    }
  }

  if (mobile.length) {
    lines.push("/* Mobilstorlek från TD / Typography – responsive. Under bp/md (1024). */");
    lines.push("@media (max-width: 1023px) {");
    for (const line of mobile) lines.push(line ? `  ${line}` : "");
    lines.push("}");
    lines.push("");
  }

  return `${lines.join("\n")}`;
}

function generate() {
  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(FONTS_FILE, generateFontsCss(), "utf8");
  writeFileSync(STYLES_FILE, generateTypographyCss(), "utf8");
  return { fonts: FONTS_FILE, typography: STYLES_FILE };
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];

if (isMain) {
  const out = generate();
  console.log(`Wrote ${out.fonts}`);
  console.log(`Wrote ${out.typography}`);
}

export { generate };
