/**
 * Generates CSS custom properties from design-system/tokens/*.json.
 * Source of truth stays in JSON (font.size in px); only CSS output uses rem for font sizes.
 */

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = join(__dirname, "..");
const TOKENS = join(ROOT, "tokens");
const OUT_DIR = join(ROOT, "generated");
const OUT_FILE = join(OUT_DIR, "tokens.css");
const BREAKPOINTS_OUT = join(OUT_DIR, "breakpoints.mjs");

/** Assumes html { font-size: 100%; } (16px root in typical browsers). */
export const REM_BASE_PX = 16;

/**
 * Breakpoint px from primitives.json — CSS custom properties cannot be used in
 * `@media`, so these are a JS/reference export only (see tokens.css comment).
 * @type {Readonly<Record<string, number>>}
 */
export const BREAKPOINTS_PX = Object.freeze({
  sm: 640,
  md: 1024,
  lg: 1280,
});

/** @param {number} px */
export function pxToRem(px) {
  if (typeof px !== "number" || Number.isNaN(px)) {
    throw new Error(`pxToRem: expected number, got ${px}`);
  }
  const rem = px / REM_BASE_PX;
  const formatted = Number(rem.toFixed(4));
  return `${formatted}rem`;
}

function loadJson(name) {
  return JSON.parse(readFileSync(join(TOKENS, name), "utf8"));
}

/** @param {Record<string, unknown>} obj @param {string} dotPath */
function getByPath(obj, dotPath) {
  return dotPath.split(".").reduce((acc, key) => {
    if (acc == null || typeof acc !== "object") return undefined;
    return /** @type {Record<string, unknown>} */ (acc)[key];
  }, /** @type {unknown} */ (obj));
}

/** @param {string} segment */
function cssVarName(...segments) {
  return `--${segments.join("-")}`;
}

/**
 * @param {Record<string, { value: string }>} group
 * @param {string[]} prefix
 */
function emitColorGroup(group, prefix) {
  const lines = [];
  for (const [key, token] of Object.entries(group)) {
    if (!token?.value) continue;
    lines.push(`  ${cssVarName(...prefix, key)}: ${token.value};`);
  }
  return lines;
}

/** @param {string} hex @param {number} alpha 0–1 */
function hexToRgba(hex, alpha) {
  const h = hex.replace("#", "");
  if (h.length !== 6) throw new Error(`hexToRgba: expected #RRGGBB, got ${hex}`);
  const r = parseInt(h.slice(0, 2), 16);
  const g = parseInt(h.slice(2, 4), 16);
  const b = parseInt(h.slice(4, 6), 16);
  const a = Number(alpha);
  if (Number.isNaN(a) || a < 0 || a > 1) {
    throw new Error(`hexToRgba: alpha must be 0–1, got ${alpha}`);
  }
  return `rgba(${r}, ${g}, ${b}, ${a})`;
}

/** @param {{ value: number; scope?: string }} token */
function opacityTokenToCss(token) {
  const v = Number(token.value);
  if (Number.isNaN(v)) {
    throw new Error(`opacityTokenToCss: expected number, got ${token.value}`);
  }
  // Figma OPACITY scope stores percent (0–100); CSS needs 0–1.
  if (token.scope === "OPACITY" || v > 1) {
    return Number((v / 100).toFixed(4));
  }
  return v;
}

function generate() {
  const primitives = loadJson("primitives.json");
  const orsa = loadJson("orsagronklitt.semantic.json");
  const tanndalen = loadJson("tanndalen.semantic.json");

  const lines = [];
  lines.push("/* Generated by scripts/generate-css-vars.mjs — do not edit by hand. */");
  lines.push("");
  lines.push("html {");
  lines.push("  font-size: 100%;");
  lines.push("}");
  lines.push("");
  lines.push(":root {");
  lines.push("  /* —— Primitives: color —— */");

  for (const [brand, group] of Object.entries(primitives.color)) {
    lines.push(...emitColorGroup(group, ["color", brand]));
  }

  lines.push("");
  lines.push("  /* —— Primitives: font.size (px in JSON → rem in CSS) —— */");
  for (const [key, px] of Object.entries(primitives.font.size)) {
    lines.push(`  ${cssVarName("font-size", key)}: ${pxToRem(px)};`);
  }

  lines.push("");
  lines.push("  /* —— Primitives: font.weight —— */");
  for (const [key, val] of Object.entries(primitives.font.weight)) {
    lines.push(`  ${cssVarName("font-weight", key)}: ${val};`);
  }

  lines.push("");
  lines.push("  /* —— Primitives: font.leading (unitless multipliers) —— */");
  for (const [key, val] of Object.entries(primitives.font.leading)) {
    if (key.startsWith("$")) continue;
    lines.push(`  ${cssVarName("font-leading", key)}: ${val};`);
  }

  lines.push("");
  lines.push("  /* —— Primitives: font.tracking (px) —— */");
  for (const [key, token] of Object.entries(primitives.font.tracking ?? {})) {
    if (key.startsWith("$")) continue;
    const px = typeof token === "object" && token !== null && "value" in token ? token.value : token;
    lines.push(`  ${cssVarName("font-tracking", key)}: ${px}px;`);
  }

  lines.push("");
  lines.push("  /* —— Primitives: font.family —— */");
  for (const [brand, families] of Object.entries(primitives.font.family)) {
    for (const [role, token] of Object.entries(families)) {
      if (!token?.value) continue;
      lines.push(
        `  ${cssVarName("font-family", brand, role)}: ${JSON.stringify(token.value)};`,
      );
    }
  }

  lines.push("");
  lines.push("  /* —— Primitives: stroke (px) —— */");
  for (const [key, px] of Object.entries(primitives.stroke ?? {})) {
    if (key.startsWith("$")) continue;
    lines.push(`  ${cssVarName("stroke", String(key).replaceAll(".", "-"))}: ${px}px;`);
  }

  lines.push("");
  lines.push("  /* —— Primitives: size (px) —— */");
  for (const [key, token] of Object.entries(primitives.size ?? {})) {
    if (key.startsWith("$") || typeof token !== "object" || token === null || !("value" in token)) continue;
    lines.push(`  ${cssVarName("size", key)}: ${token.value}px;`);
  }

  lines.push("");
  lines.push("  /* —— Primitives: opacity (Figma OPACITY % → CSS 0–1) —— */");
  for (const [key, token] of Object.entries(primitives.opacity ?? {})) {
    if (key.startsWith("$") || typeof token !== "object" || token === null || !("value" in token)) continue;
    lines.push(`  ${cssVarName("opacity", key)}: ${opacityTokenToCss(/** @type {{ value: number; scope?: string }} */ (token))};`);
  }

  lines.push("");
  lines.push("  /* —— Primitives: radius (px) —— */");
  for (const [key, px] of Object.entries(primitives.radius ?? {})) {
    if (key.startsWith("$") || typeof px !== "number") continue;
    lines.push(`  ${cssVarName("radius", key)}: ${px}px;`);
  }

  lines.push("");
  lines.push("  /* —— Primitives: z-index —— */");
  for (const [key, val] of Object.entries(primitives.z ?? {})) {
    if (key.startsWith("$") || typeof val !== "number") continue;
    lines.push(`  ${cssVarName("z", key)}: ${val};`);
  }

  lines.push("");
  lines.push("  /* —— Primitives: motion —— */");
  for (const [key, token] of Object.entries(primitives.motion ?? {})) {
    if (key.startsWith("$") || typeof token !== "object" || token === null || !("value" in token)) continue;
    if (key.startsWith("duration-")) {
      lines.push(`  ${cssVarName("motion", key)}: ${token.value}ms;`);
    } else {
      lines.push(`  ${cssVarName("motion", key)}: ${token.value};`);
    }
  }
  lines.push("");
  lines.push("  @media (prefers-reduced-motion: reduce) {");
  lines.push("    --motion-duration-fast: 0ms;");
  lines.push("    --motion-duration-normal: 0ms;");
  lines.push("    --motion-duration-slow: 0ms;");
  lines.push("  }");

  const bpEntries = Object.entries(primitives.breakpoint ?? {}).filter(
    ([key, token]) => !key.startsWith("$") && token && typeof token === "object" && "value" in token,
  );
  lines.push("");
  lines.push("  /*");
  lines.push("   * Breakpoints (Figma bp/*) — referens only.");
  lines.push("   * CSS custom properties cannot be used in @media queries.");
  lines.push("   * Values also exported as generated/breakpoints.mjs (BREAKPOINTS_PX).");
  for (const [key, token] of bpEntries) {
    const px = /** @type {{ value: number; purpose?: string }} */ (token).value;
    const purpose = /** @type {{ purpose?: string }} */ (token).purpose;
    lines.push(`   * bp/${key} = ${px}px${purpose ? ` — ${purpose}` : ""}`);
  }
  lines.push("   */");

  lines.push("}");
  lines.push("");

  /**
   * Emit semantic alias group (color / status / contrast) as CSS vars pointing at primitives.
   * @param {string} brandKey
   * @param {Record<string, unknown>} group
   * @param {string[]} cssPrefix
   * @param {string[]} linesOut
   */
  function emitSemanticRefs(brandKey, group, cssPrefix, linesOut) {
    if (!group || typeof group !== "object") return;
    for (const [role, token] of Object.entries(group)) {
      if (role.startsWith("$") || typeof token !== "object" || token === null) continue;

      // Direct CSS value (e.g. frost rgba) — no alias.
      if ("value" in token && typeof token.value === "string" && !("ref" in token)) {
        linesOut.push(`  ${cssVarName(...cssPrefix, role)}: ${token.value};`);
        continue;
      }
      if (!("ref" in token)) continue;

      const ref = /** @type {{ ref: string; alpha?: number }} */ (token).ref;
      const alpha = /** @type {{ alpha?: number }} */ (token).alpha;
      const resolved = getByPath(primitives, ref);
      const hex =
        resolved && typeof resolved === "object" && "value" in resolved
          ? /** @type {{ value: string }} */ (resolved).value
          : null;
      if (!hex) {
        throw new Error(`${brandKey}: unresolved ref ${ref} for ${cssPrefix.join("/")}/${role}`);
      }
      if (typeof alpha === "number") {
        linesOut.push(`  ${cssVarName(...cssPrefix, role)}: ${hexToRgba(hex, alpha)};`);
      } else {
        const primitiveVar = cssVarName(...ref.replace(/^color\./, "color-").split("."));
        linesOut.push(`  ${cssVarName(...cssPrefix, role)}: var(${primitiveVar});`);
      }
    }
  }

  for (const [brandKey, semantic, className] of [
    ["OG", orsa, "theme-OG"],
    ["TD", tanndalen, "theme-TD"],
  ]) {
    lines.push(`.${className} {`);
    lines.push(`  /* —— Semantic colors: ${brandKey} —— */`);
    emitSemanticRefs(brandKey, semantic.color, ["color"], lines);

    if (semantic.status) {
      lines.push("");
      lines.push(`  /* —— Status: ${brandKey} —— */`);
      emitSemanticRefs(brandKey, semantic.status, ["status"], lines);
    }

    if (semantic.contrast) {
      lines.push("");
      lines.push(`  /* —— Contrast on-*: ${brandKey} —— */`);
      emitSemanticRefs(brandKey, semantic.contrast, ["contrast"], lines);
    }

    if (semantic.difficulty) {
      lines.push("");
      lines.push(`  /* —— Difficulty: ${brandKey} —— */`);
      emitSemanticRefs(brandKey, semantic.difficulty, ["difficulty"], lines);
    }

    if (semantic.wax) {
      lines.push("");
      lines.push(`  /* —— Wax: ${brandKey} —— */`);
      emitSemanticRefs(brandKey, semantic.wax, ["wax"], lines);
    }

    lines.push("");
    lines.push(`  /* —— Spacing: ${brandKey} (px) —— */`);
    for (const [key, token] of Object.entries(primitives.space ?? {})) {
      if (key.startsWith("$") || typeof token !== "object" || token === null) continue;
      const px = /** @type {Record<string, number>} */ (token)[brandKey];
      if (typeof px !== "number") continue;
      lines.push(`  ${cssVarName("space", key)}: ${px}px;`);
    }

    lines.push("}");
    lines.push("");
  }

  /** @type {Record<string, number>} */
  const bpPx = {};
  for (const [key, token] of bpEntries) {
    bpPx[key] = /** @type {{ value: number }} */ (token).value;
  }
  const bpFile = [
    "/* Generated by scripts/generate-css-vars.mjs — do not edit by hand. */",
    "/** Figma bp/* — use in JS / hardcode in @media; not valid as CSS vars in queries. */",
    `export const BREAKPOINTS_PX = Object.freeze(${JSON.stringify(bpPx, null, 2)});`,
    "",
  ].join("\n");

  mkdirSync(OUT_DIR, { recursive: true });
  writeFileSync(OUT_FILE, `${lines.join("\n")}\n`, "utf8");
  writeFileSync(BREAKPOINTS_OUT, bpFile, "utf8");
  return OUT_FILE;
}

const isMain = process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];

if (isMain) {
  const out = generate();
  console.log(`Wrote ${out}`);
  console.log(`Wrote ${BREAKPOINTS_OUT}`);
}
